import assert from "node:assert/strict";
import {build} from "esbuild";

const {outputFiles} = await build({entryPoints:["lib/pages-api.ts"],bundle:true,format:"esm",platform:"node",write:false});
const {pagesRequest} = await import("data:text/javascript;base64,"+Buffer.from(outputFiles[0].contents).toString("base64"));
const store=new Map();
globalThis.localStorage={getItem:key=>store.get(key)??null,setItem:(key,value)=>store.set(key,value)};
const request=(person,method,path,body)=>pagesRequest("conferences/uist-demo/"+path,method,person,body);
const get=(person,path)=>request(person,"GET",path);
const set=(field,value)=>assert.equal(request("mira","PATCH","me/sharing",{field,value}).status,200);
const hasMira=path=>get("leo",path).data.attendees.some(p=>p.id==="mira");
assert.equal(get("leo","attendees/mira").status,404);
assert.equal(get("guest","attendees/leo").status,403);
assert.equal(hasMira("attendees"),false);
assert.deepEqual(get("mira","attendees/leo").data.profile.authored,["p1"]);
set("profile",true);
assert.equal(hasMira("attendees"),true);
assert.equal(hasMira("attendees?paper=p1"),false);
assert.equal(hasMira("attendees?session=s1"),false);
set("list.reading",true);
set("session.s1",{going:true,shared:true});
assert.equal(hasMira("attendees?paper=p1"),true);
assert.equal(hasMira("attendees?session=s1"),true);
const profile=get("leo","attendees/mira").data.profile;
assert.deepEqual(profile.lists.map(l=>l.id),["reading"]);
assert.deepEqual(profile.shared,["s1"]);
assert.ok(!("going" in profile) && !("saved" in profile));
assert.equal(request("mira","POST","messages",{recipient:"leo",body:"Meet after the session?"}).status,201);
assert.equal(get("leo","state").data.messages[0].body,"Meet after the session?");
assert.deepEqual(get("guest","state").data.messages,[]);
set("list.reading",false);
assert.equal(hasMira("attendees?paper=p1"),false);
assert.equal(hasMira("attendees?session=s1"),true);
set("profile",false);
assert.equal(get("leo","attendees/mira").status,404);
assert.equal(hasMira("attendees?session=s1"),false);
assert.deepEqual(get("mira","state").data.own.shared,["s1"]);
assert.equal(request("leo","POST","messages",{recipient:"mira",body:"hello"}).status,404);
assert.equal(request("leo","PATCH","me/sharing",{field:"session.s1",value:{going:false,shared:true}}).status,400);
assert.equal(request("leo","PATCH","me/sharing",{field:"links",value:{website:"javascript:alert(1)",scholar:""}}).status,400);
console.log("Passed directory, attendance, list, download, identity, revocation and message checks.");
